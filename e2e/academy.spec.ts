import { test, expect } from '@playwright/test'

test('docente publica, estudiante entrega y docente revisa', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page.getByRole('heading', { name: 'Buen día, Lucía' })).toBeVisible()
  await page.getByRole('link', { name: 'Evaluaciones', exact: true }).click()
  await page.getByRole('link', { name: 'Nueva evaluación' }).click()
  await page.getByLabel('Título de la evaluación').fill('Prueba integral E2E')
  await page.getByLabel('Enunciado').fill('¿Cuánto es dos más dos?')
  await page.getByPlaceholder('Opción 1').fill('3')
  await page.getByPlaceholder('Opción 2').fill('4')
  await page.getByLabel('Respuesta correcta opción 2').check()
  await page.getByRole('button', { name: 'Añadir pregunta' }).click()
  await page.getByLabel('Enunciado').nth(1).fill('Explica tu procedimiento.')
  await page.getByLabel('Tipo').nth(1).selectOption('short')
  await page.getByRole('button', { name: /Publicar evaluación/ }).click()
  await expect(page.getByText('Prueba integral E2E')).toBeVisible()
  await page.getByRole('button', { name: /Lucía Fernández/ }).click()
  await page.getByRole('link', { name: /Ingresar como estudiante/ }).click()
  await page.getByRole('button', { name: 'Usar código ACD-2048' }).click()
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await page.getByRole('link', { name: 'Evaluaciones', exact: true }).click()
  await page.locator('.student-exam-card').filter({ hasText: 'Prueba integral E2E' }).getByRole('link', { name: /Comenzar evaluación/ }).click()
  await page.getByRole('button', { name: /Comenzar ahora/ }).click()
  await page.getByRole('button', { name: 'B 4' }).click()
  await page.getByRole('button', { name: /Siguiente/ }).click()
  await page.getByPlaceholder('Escribe tu respuesta aquí…').fill('Sumé dos y dos.')
  await page.reload()
  await page.getByRole('button', { name: '2', exact: true }).click()
  await expect(page.getByPlaceholder('Escribe tu respuesta aquí…')).toHaveValue('Sumé dos y dos.')
  await page.getByRole('button', { name: /Entregar evaluación/ }).click()
  await page.getByRole('button', { name: 'Confirmar' }).click()
  await expect(page.getByText('¡Buen trabajo!')).toBeVisible()
  await page.getByRole('button', { name: /Camila Rojas/ }).click()
  await page.getByRole('link', { name: /Soy docente o administrador/ }).click()
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await page.getByRole('link', { name: 'Resultados' }).click()
  await page.getByRole('row', { name: /Prueba integral E2E/ }).getByRole('button', { name: 'Revisar' }).click()
  await page.getByLabel('Calificación (0–1)').fill('1')
  await page.getByRole('button', { name: 'Guardar revisión' }).click()
  await expect(page.getByRole('row', { name: /Prueba integral E2E/ }).getByText('Calificado')).toBeVisible()
})

test('administrador crea estudiante, muestra QR y desactiva acceso', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: 'Administrador' }).click()
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await page.getByRole('link', { name: 'Estudiantes', exact: true }).click()
  await page.getByRole('button', { name: 'Nuevo estudiante' }).click()
  await page.getByLabel('Nombre completo').fill('Elena Demo')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  const row = page.getByRole('row', { name: /Elena Demo/ })
  const code = await row.locator('code').textContent()
  expect(code).toMatch(/^ACD-\d{4}$/)
  await row.getByRole('button', { name: 'QR' }).click()
  await expect(page.getByRole('dialog').locator('svg[role="img"]')).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar' }).click()
  await row.getByRole('button', { name: 'Desactivar' }).click()
  await page.getByRole('button', { name: 'Confirmar' }).click()
  await expect(row.getByText('Inactivo')).toBeVisible()
  await page.getByRole('button', { name: /Valeria Medina/ }).click()
  await page.getByRole('link', { name: /Ingresar como estudiante/ }).click()
  await page.getByLabel('Código de acceso').fill(code!)
  await page.getByRole('button', { name: 'Ingresar' }).click()
  await expect(page.getByRole('alert')).toContainText('cuenta desactivada')
})
